/**
 * Returns video reels for any destination by ID or generates a curated video fallback
 */
export function getVideosForDestination(dest) {
  if (!dest) return [];

  // Check direct mapped list
  if (PLACE_VIDEOS_MAP[dest.id]) {
    return PLACE_VIDEOS_MAP[dest.id];
  }

  // Check if destination has embedded reels
  if (dest.reels && dest.reels.length > 0) {
    return dest.reels;
  }

  // Category-based high-quality curated fallback
  const isWater = dest.category === 'Beach' || dest.tags?.includes('beach') || dest.tags?.includes('ocean');
  const isTemple = dest.category === 'Temple' || dest.category === 'Heritage' || dest.tags?.includes('temple');
  const isFood = dest.category === 'Foodie' || dest.tags?.includes('food');

  const defaultVideo = isWater
    ? 'https://assets.mixkit.co/videos/preview/mixkit-waves-in-the-water-1164-large.mp4'
    : isTemple
      ? 'https://assets.mixkit.co/videos/preview/mixkit-smoke-and-fire-particles-in-the-dark-41584-large.mp4'
      : isFood
        ? 'https://assets.mixkit.co/videos/preview/mixkit-top-view-of-a-table-with-traditional-food-43555-large.mp4'
        : 'https://assets.mixkit.co/videos/preview/mixkit-forest-stream-in-the-sunlight-529-large.mp4';

  return [
    {
      id: `v-gen-${dest.id}`,
      title: `Cinematic Tour of ${dest.name} 🌟`,
      creator: `@smarttour_${dest.city?.toLowerCase().replace(/\s+/g, '_') || 'explorer'}`,
      videoUrl: defaultVideo,
      thumbnail: dest.image || 'https://images.unsplash.com/photo-1506744038136-46273834b3fb?w=800&q=80',
      views: '120K',
      likes: '15.4K',
      song: 'Tamil Nadu Tourism Anthem & Vibes',
      duration: '0:30',
      placeName: dest.name,
      placeCity: dest.city
    }
  ];
}
